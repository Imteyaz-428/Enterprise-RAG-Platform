class MockFailingProvider(BaseProvider):
    def __init__(self, exception_to_raise: Exception):
        self.exception_to_raise = exception_to_raise
        self.generate_call_count = 0
        self.stream_call_count = 0

    def generate(self, prompt: str) -> str:
        self.generate_call_count += 1
        raise self.exception_to_raise

    def stream(self, prompt: str):
        self.stream_call_count += 1
        raise self.exception_to_raise


class MockSuccessProvider(BaseProvider):
    def __init__(self, answer: str = "Successful response", tokens: list[str] | None = None):
        self.answer = answer
        self.tokens = tokens or ["Hello", " from", " AI"]
        self.generate_call_count = 0
        self.stream_call_count = 0

    def generate(self, prompt: str) -> str:
        self.generate_call_count += 1
        return self.answer

    def stream(self, prompt: str):
        self.stream_call_count += 1
        for token in self.tokens:
            yield token


class MockMidStreamFailingProvider(BaseProvider):
    def __init__(self, tokens_before_fail: list[str], failure_exc: Exception):
        self.tokens_before_fail = tokens_before_fail
        self.failure_exc = failure_exc

    def generate(self, prompt: str) -> str:
        return "mid stream provider"

    def stream(self, prompt: str):
        for token in self.tokens_before_fail:
            yield token
        raise self.failure_exc


@pytest.fixture
def ai_service():
    service = AIService()
