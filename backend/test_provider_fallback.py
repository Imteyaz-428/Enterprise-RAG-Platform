def test_gemini_failure_groq_success(ai_service):
    """When Gemini fails with 401, AIService falls back to Groq and succeeds."""
    gemini_mock = MockFailingProvider(Exception("401 UNAUTHENTICATED: API key not valid"))
    groq_mock = MockSuccessProvider("Answer generated by Groq")

    ai_service.provider_instances = {
        "gemini": gemini_mock,
        "groq": groq_mock,
    }

    result = ai_service.generate_answer("Hello", providers=["gemini", "groq"])

    assert result == "Answer generated by Groq"
    assert gemini_mock.generate_call_count == 1
    assert groq_mock.generate_call_count == 1


def test_gemini_and_groq_failure_deepseek_success(ai_service):
    """When Gemini and Groq both fail, AIService falls back to DeepSeek and succeeds."""
    gemini_mock = MockFailingProvider(Exception("401 UNAUTHENTICATED"))
    groq_mock = MockFailingProvider(Exception("503 Service Unavailable"))
    deepseek_mock = MockSuccessProvider("Answer generated by DeepSeek")

    ai_service.provider_instances = {
        "gemini": gemini_mock,
        "groq": groq_mock,
        "deepseek": deepseek_mock,
    }

    result = ai_service.generate_answer("Hello", providers=["gemini", "groq", "deepseek"])

    assert result == "Answer generated by DeepSeek"
    assert deepseek_mock.generate_call_count == 1


def test_all_providers_failure_raises_ai_provider_error(ai_service):
    """When all providers fail, AIProviderError is raised with categorized error details."""
    gemini_mock = MockFailingProvider(Exception("401 UNAUTHENTICATED"))
    groq_mock = MockFailingProvider(Exception("429 Rate limit reached"))
    deepseek_mock = MockFailingProvider(Exception("402 Insufficient Balance"))

    ai_service.provider_instances = {
        "gemini": gemini_mock,
        "groq": groq_mock,
        "deepseek": deepseek_mock,
    }

    with pytest.raises(AIProviderError) as exc_info:
        ai_service.generate_answer("Hello", providers=["gemini", "groq", "deepseek"])

    err_msg = str(exc_info.value)
    assert "All AI providers failed" in err_msg
    assert "gemini (authentication:" in err_msg
    assert "groq (rate_limit:" in err_msg
    assert "deepseek (billing:" in err_msg


def test_empty_response_triggers_fallback(ai_service):
    """When a provider returns an empty string or whitespace, it fails over to the next provider."""
    gemini_empty = MockSuccessProvider(answer="   ")
    groq_success = MockSuccessProvider(answer="Valid answer from Groq")

    ai_service.provider_instances = {
        "gemini": gemini_empty,
        "groq": groq_success,
    }

    result = ai_service.generate_answer("Hello", providers=["gemini", "groq"])
    assert result == "Valid answer from Groq"


