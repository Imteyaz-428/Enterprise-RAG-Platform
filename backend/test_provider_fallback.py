def test_streaming_fallback_before_first_token(ai_service):
    """When Gemini stream fails on init, Groq stream takes over and yields all tokens."""
    gemini_mock = MockFailingProvider(Exception("401 Invalid API Key"))
    groq_mock = MockSuccessProvider(tokens=["Streaming ", "from ", "Groq!"])

    ai_service.provider_instances = {
        "gemini": gemini_mock,
        "groq": groq_mock,
    }

    stream = ai_service.stream_answer("Hello", providers=["gemini", "groq"])
    collected_tokens = list(stream)

    assert "".join(collected_tokens) == "Streaming from Groq!"
    assert gemini_mock.stream_call_count == 1
    assert groq_mock.stream_call_count == 1


def test_streaming_all_providers_fail(ai_service):
    """When all providers fail to initialize stream, AIProviderError is raised before any token."""
    gemini_mock = MockFailingProvider(Exception("401 UNAUTHENTICATED"))
    groq_mock = MockFailingProvider(Exception("401 Invalid Key"))
    deepseek_mock = MockFailingProvider(Exception("402 Insufficient Balance"))

    ai_service.provider_instances = {
        "gemini": gemini_mock,
        "groq": groq_mock,
        "deepseek": deepseek_mock,
    }

    with pytest.raises(AIProviderError) as exc_info:
        # Consuming the generator triggers the initial connection attempt
        list(ai_service.stream_answer("Hello", providers=["gemini", "groq", "deepseek"]))

    err_msg = str(exc_info.value)
    assert "All AI providers failed to generate stream" in err_msg
    assert "authentication" in err_msg
    assert "billing" in err_msg


def test_streaming_midstream_failure_does_not_switch_provider(ai_service):
    """
    Once the first token has been yielded to the client, the provider is committed.
    A mid-stream connection loss must raise an exception rather than silently switching providers.
    """
    midstream_gemini = MockMidStreamFailingProvider(
        tokens_before_fail=["Token 1", " Token 2"],
        failure_exc=ConnectionResetError("Socket reset mid-stream"),
    )
    groq_mock = MockSuccessProvider(tokens=["Groq Token 1", " Groq Token 2"])

    ai_service.provider_instances = {
        "gemini": midstream_gemini,
        "groq": groq_mock,
    }

    gen = ai_service.stream_answer("Hello", providers=["gemini", "groq"])
    
    first = next(gen)
    assert first == "Token 1"
    second = next(gen)
    assert second == " Token 2"

    with pytest.raises(ConnectionResetError):
        next(gen)

    # Groq must NOT have been called mid-stream
    assert groq_mock.stream_call_count == 0


def test_empty_stream_triggers_fallback(ai_service):
    """If a provider stream yields no non-empty tokens, it fails over to the next provider."""
    gemini_empty_stream = MockSuccessProvider(tokens=["", "  "])
    groq_mock = MockSuccessProvider(tokens=["Valid ", "stream"])

    ai_service.provider_instances = {
        "gemini": gemini_empty_stream,
        "groq": groq_mock,
    }

    tokens = list(ai_service.stream_answer("Hello", providers=["gemini", "groq"]))
    assert "".join(tokens) == "Valid stream"


