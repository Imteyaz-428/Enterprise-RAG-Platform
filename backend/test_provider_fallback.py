def test_transient_error_classification():
    """Verify transient vs permanent classification."""
    # Permanent errors (no retry)
    assert is_transient_error(ValueError("401 Unauthorized")) is False
    assert is_transient_error(ValueError("402 Insufficient Balance")) is False
    assert is_transient_error(ValueError("403 Forbidden")) is False
    assert is_transient_error(ValueError("404 Not Found")) is False

    # Transient errors (retry with backoff)
    assert is_transient_error(ValueError("429 Rate limit exceeded")) is True
    assert is_transient_error(ValueError("503 Service Unavailable")) is True
    assert is_transient_error(TimeoutError("Connection timed out")) is True
    assert is_transient_error(ConnectionError("Connection reset by peer")) is True


def test_error_category_classification():
    """Verify standardized failure categories."""
    assert classify_provider_error(Exception("401 Unauthorized: Invalid API Key")) == "authentication"
    assert classify_provider_error(Exception("402 Insufficient Balance")) == "billing"
    assert classify_provider_error(Exception("429 Resource Exhausted: Quota exceeded")) == "rate_limit"
    assert classify_provider_error(TimeoutError("Request timed out after 30s")) == "timeout"
    assert classify_provider_error(Exception("500 Internal Server Error")) == "server_error"
    assert classify_provider_error(ValueError("GROQ_API_KEY is not configured")) == "configuration"


def test_secret_sanitization():
    """Verify API keys and tokens are masked."""
    with patch.dict(os.environ, {"GEMINI_API_KEY": "AIzaSySecretGeminiKey123"}):
        err = "Failed with key AIzaSySecretGeminiKey123 in request"
        sanitized = AIService._sanitize_error(err)
        assert "AIzaSySecretGeminiKey123" not in sanitized
        assert "[REDACTED]" in sanitized

    auth_err = "Authorization: Bearer mySecretToken987654 failed"
    sanitized_auth = AIService._sanitize_error(auth_err)
    assert "mySecretToken987654" not in sanitized_auth
    assert "[REDACTED]" in sanitized_auth


